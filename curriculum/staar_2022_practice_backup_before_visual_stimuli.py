# TEKS grouping helpers for STAAR Practice Library
def staar_teks_sort_key(teks):
    import re

    teks = str(teks or "").strip().upper()
    match = re.match(r"(\d+)\.(\d+)\(?([A-Z])\)?", teks)

    if not match:
        return (999, 999, "Z", teks)

    grade = int(match.group(1))
    standard = int(match.group(2))
    letter = match.group(3)

    return (grade, standard, letter, teks)


def normalize_staar_teks(teks):
    teks = str(teks or "").strip().upper()
    teks = teks.replace("(", "").replace(")", "")

    return teks


def group_staar_questions_by_teks(questions):
    grouped = {}

    for question in questions:
        teks = normalize_staar_teks(question.get("source_teks", "Unlisted"))
        grouped.setdefault(teks, []).append(question)

    result = []

    for teks in sorted(grouped.keys(), key=staar_teks_sort_key):
        result.append({
            "teks": teks,
            "questions": sorted(grouped[teks], key=lambda q: (str(q.get("year", "2022")), int(q.get("item", 0))))
        })

    return result
# End TEKS grouping helpers for STAAR Practice Library


# Grade dropdown grouping helpers for STAAR Practice Library
def staar_grade_label_from_teks(teks):
    teks = normalize_staar_teks(teks)

    if teks.startswith("3."):
        return "3rd Grade TEKS"

    if teks.startswith("4."):
        return "4th Grade TEKS"

    if teks.startswith("5."):
        return "5th Grade TEKS"

    return "Other TEKS"


def staar_grade_sort_key(grade_label):
    if grade_label.startswith("3rd"):
        return 3

    if grade_label.startswith("4th"):
        return 4

    if grade_label.startswith("5th"):
        return 5

    return 99


def group_staar_questions_by_grade_and_teks(questions):
    grade_groups = {}

    for question in questions:
        teks = normalize_staar_teks(question.get("source_teks", "Unlisted"))
        grade_label = staar_grade_label_from_teks(teks)

        grade_groups.setdefault(grade_label, {})
        grade_groups[grade_label].setdefault(teks, [])
        grade_groups[grade_label][teks].append(question)

    result = []

    for grade_label in sorted(grade_groups.keys(), key=staar_grade_sort_key):
        teks_groups = []

        for teks in sorted(grade_groups[grade_label].keys(), key=staar_teks_sort_key):
            teks_groups.append({
                "teks": teks,
                "questions": sorted(
                    grade_groups[grade_label][teks],
                    key=lambda q: (str(q.get("year", "2022")), int(q.get("item", 0)))
                )
            })

        result.append({
            "grade_label": grade_label,
            "teks_groups": teks_groups,
            "question_count": sum(len(group["questions"]) for group in teks_groups)
        })

    return result
# End grade dropdown grouping helpers for STAAR Practice Library

