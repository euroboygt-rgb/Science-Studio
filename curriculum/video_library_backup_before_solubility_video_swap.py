def add_video_links(video):
    video = dict(video)
    video["embed_url"] = f"https://www.youtube-nocookie.com/embed/{video['youtube_id']}"
    video["watch_url"] = f"https://www.youtube.com/watch?v={video['youtube_id']}"
    return video


def get_video_by_slug(slug):
    video = SCIENCE_VIDEO_LIBRARY.get(slug)
    if not video:
        return None

    video = add_video_links(video)
    video["slug"] = slug
    return video


def get_videos_for_day(day):
    try:
        day = int(day)
    except Exception:
        return []

    slugs = DAY_VIDEO_MAP.get(day, [])
    videos = []

    for slug in slugs:
        video = get_video_by_slug(slug)
        if video:
            videos.append(video)

    return videos


def get_all_videos():
    videos = []

    for slug, video in SCIENCE_VIDEO_LIBRARY.items():
        v = add_video_links(video)
        v["slug"] = slug
        videos.append(v)

    return videos
